import { GoogleGenerativeAI } from "@google/generative-ai";
import { ScrapedData } from "./types";

export async function generateAiAnalysis(
  data: ScrapedData,
  score: number,
  url: string,
  geminiApiKey: string
): Promise<{ 
  score: number; 
  pageCategory: string; 
  aiAnalysis: string; 
  recommendations: {
    id: string;
    title: string;
    severity: "CRITICAL" | "MEDIUM" | "LOW";
    category: "Technical" | "Semantic Layout" | "Entity & Trust" | "Content Optimization";
    description: string;
    impact: string;
    fixSteps: string[];
    codeSnippet?: string;
  }[]; // ✨ Promijenjeno iz string[] u niz objekata
  bluffScore: number;
  atomicStructureScore: number;
  entityDensityScore: number;
  sentenceSimplicityScore: number;
  commodityContentScore: number;
}> {
  const genAI = new GoogleGenerativeAI(geminiApiKey);

  type GeminiSchema = NonNullable<
    NonNullable<Parameters<typeof genAI.getGenerativeModel>[0]["generationConfig"]>["responseSchema"]
  >;

  const aeoResponseSchema = {
    type: "OBJECT",
    properties: {
      score: {
        type: "INTEGER",
        description: "The finalized AEO visibility score from 0 to 100, refining the initial seed score based on industry standards."
      },
      pageCategory: {
        type: "STRING",
        description: "The exact classification of the website (e.g., 'Personal Portfolio', 'Local Business', 'E-commerce', 'SaaS Platform', 'Health & Medical Blog', 'Niche Content Blog')."
      },
      aiAnalysis: {
        type: "STRING",
        description: "Executive synthesis audit looking deeply at LLM crawlability, semantic HTML structures, heading cascade rules, multimodal image alt tags, and graph optimizations.",
      },
      bluffScore: { 
        type: "INTEGER", 
        description: "Score 1-10. Assesses if sections start with a direct answer (Bottom Line Up Front) instead of burying points in backstory." 
      },
      atomicStructureScore: { 
        type: "INTEGER", 
        description: "Score 1-10. Assesses if H2/H3 sections make complete sense when read entirely out of context (ready for LLM chunking)." 
      },
      entityDensityScore: { 
        type: "INTEGER", 
        description: "Score 1-10. Assesses how rich the content is with specific entities (brands, concrete concepts) vs generic filler language." 
      },
      sentenceSimplicityScore: { 
        type: "INTEGER", 
        description: "Score 1-10. Assesses if sentences are short, declarative, and easy for an LLM to parse (one idea per sentence)." 
      },
      commodityContentScore: { 
        type: "INTEGER", 
        description: "Score 1-10. 1 means pure commodity/recycled text easily generated by basic AI. 10 means highly unique, expert-led, non-commodity content with first-hand experience or data." 
      },
      // 🚀 STRUKTURIRANI OBJEKAT ZA PREPORUKE KOJI AGENCIJE ŽELE
      recommendations: {
        type: "ARRAY",
        description: "List of exactly 5 highly specific, tactical adjustments needed to rank across modern answer engines, prioritized by severity.",
        items: {
          type: "OBJECT",
          properties: {
            id: { type: "STRING", description: "Unique snake_case identifier (e.g., 'cf_block', 'missing_faq_schema')." },
            title: { type: "STRING", description: "Short, direct title of the issue." },
            severity: { type: "STRING", enum: ["CRITICAL", "MEDIUM", "LOW"], description: "CRITICAL for bot blocks, MEDIUM for schema/layout breaks, LOW for text fine-tuning." },
            category: { type: "STRING", enum: ["Technical", "Semantic Layout", "Entity & Trust", "Content Optimization"] },
            description: { type: "STRING", description: "Detailed explanation of what is wrong on the site." },
            impact: { type: "STRING", description: "How this directly impacts tokenization, context windows, or AEO discovery." },
            fixSteps: {
              type: "ARRAY",
              items: { type: "STRING" },
              description: "Step-by-step ordered list of instructions on how a developer or SEO can fix this issue."
            },
            codeSnippet: { type: "STRING", description: "Optional: JSON-LD script string, HTML snippet, or robots.txt directive exemplifying the fix. Pass empty or omit if not applicable." }
          },
          required: ["id", "title", "severity", "category", "description", "impact", "fixSteps"]
        }
      },
    },
    required: [
      "score", 
      "pageCategory", 
      "aiAnalysis", 
      "bluffScore", 
      "atomicStructureScore", 
      "entityDensityScore", 
      "sentenceSimplicityScore", 
      "commodityContentScore",
      "recommendations"
    ],
  };

  const model = genAI.getGenerativeModel({
    model: "gemini-2.5-flash-lite",
    generationConfig: {
      temperature: 0.15,
      responseMimeType: "application/json",
      responseSchema: aeoResponseSchema as unknown as GeminiSchema,
    },
  });

  const botDetected = data.aiAccessibility?.cloudflareDetected ?? false;
  const botSeverity = data.aiAccessibility?.cloudflareSeverity ?? "None";
  const botAccessStatus = data.aiAccessibility?.accessibilityStatus ?? "Unknown";
  const robotsBlockingAI = data.robotsStatus === "Blocking AI";

  const completelyBlocked = robotsBlockingAI || (botDetected && botSeverity === "Hard");
  const partiallyBlocked = !completelyBlocked && botDetected && botSeverity === "Soft";

  const botProtectionLine = botDetected
    ? `DETECTED — ${botSeverity} block (${botAccessStatus})`
    : "None detected";

  // 📝 UNAPREĐENI PROMPT ZA GENERISANJE STRUKTURIRANIH POLJA
const prompt = `
You are an expert Senior Answer Engine Optimisation (AEO) strategist.
Analyze the target website data context provided and perform a highly specific structural alignment audit tailored strictly to the website's industry and business model.

WEBSITE: ${url}
DETECTOR CONTEXT: The scraper has algorithmically identified this page layout as a **${data.pageType}**.
ROBOTS.TXT STATUS: ${data.robotsStatus}
BOT PROTECTION STATUS: ${botProtectionLine}
BOT ACCESSIBILITY STATUS: ${botAccessStatus}
TITLE: ${data.title}
META DESCRIPTION: ${data.metaDescription}
H1: ${data.h1}
DETECTED EXPLICIT Q&A CONTENT BLOCKS: ${data.qaBlocksCount}
HAS TABLE OR BULLET GRAPH STRUCTURES: ${data.hasTablesOrLists}
DETECTED SCHEMA ENTITIES: ${data.detectedSchemas.join(", ") || "None"}

SEMANTIC LAYOUT MAP:
Has Strict Main Tag: ${data.semanticLayoutMap.hasMainTag}
Has Article Container Tag: ${data.semanticLayoutMap.hasArticleTag}
Has Bad Heading Leap (Cascade Failure): ${data.semanticLayoutMap.hasHeadingLeap}
Total Images Scanned: ${data.semanticLayoutMap.totalImages}
Images Missing Description (Alt Tag): ${data.semanticLayoutMap.missingAltCount}

KNOWLEDGE GRAPH FOOTPRINT MAP:
Authority Reference Outlinks (Wikipedia/Wikidata): ${data.entityTrustMap.hasWikidataOrWikipedia}
LinkedIn Identity Profile: ${data.entityTrustMap.hasLinkedIn}
X/Twitter Profile Anchor: ${data.entityTrustMap.hasXAccount}
Facebook Profile Anchor: ${data.entityTrustMap.hasFacebookAccount}
Brand Disambiguation Status: ${data.entityTrustMap.brandDisambiguationStatus}
Identified Raw Brand Variants Across Code Contexts: ${data.entityTrustMap.detectedBrandVariants.join(", ")}

CONTENT MAP SAMPLE:
${data.bodyText}

COMPUTED SEED OPTIMIZATION SCORE: ${score}/100

CRITICAL CONTEXTUAL SCORING RULES:
1. You MUST evaluate the website quality based on the detected layout context (**${data.pageType}**).
2. If the pageType is 'Homepage' or 'Commercial' and it explicitly represents an online software tool or a purely digital SaaS platform (like an AI auditing platform), do NOT penalize the final visibility score or authority metrics for missing physical signals (address/phone) or brand-owned social profile links (LinkedIn/X profile maps) IF the JSON-LD schema graph layout is clean, valid, and present.
3. If it is a Homepage, focus your evaluation heavily on brand identity token consistency across metadata, headings, and code. Do NOT expect or penalize for the lack of long-form editorial content.
4. ${completelyBlocked
    ? `CRITICAL ACCESS OVERRIDE: This site is COMPLETELY BLOCKED to AI crawlers — either by robots.txt directive or a confirmed Hard bot protection wall. The final score MUST be 20 or below, regardless of any other positive signals. Schema quality, content depth, semantic markup — none of it matters if AI cannot access the site. Your top recommendation MUST address fixing bot access as the single most urgent priority before anything else.`
    : partiallyBlocked
    ? `PARTIAL ACCESS WARNING: A Soft bot protection block has been detected. Most AI crawlers operate from datacenter IPs and will be blocked in practice. Cap the final score at 50 regardless of other positive signals. Your top recommendation MUST address resolving the bot protection wall before any content or schema optimizations.`
    : `Bot access is clean. Evaluate and score normally based on content, schema, and semantic structure.`
  }
5. If BOT PROTECTION STATUS shows any block, do NOT recommend schema tweaks, content improvements, or semantic optimizations as the primary fix. Bot access resolution must always be recommendation #1 when a block is present.

STRICT AEO WRITING RUBRIC (For Scoring Content Sample):
You MUST calculate the 5 core pillar scores strictly using the following mathematical anchor rules based on the provided CONTENT MAP SAMPLE:
- bluffScore (1-10): Rate 1-3 if the text has high fluff, repetitive phrases, or introductory filler. Rate 8-10 ONLY if the text delivers immediate, direct answers in the first 2 sentences.
- atomicStructureScore (1-10): Rate 1-4 if it is raw, unbroken paragraphs. Rate 8-10 if it contains clear headers, bolded semantic keyphrases, and bullet points/tables.
- entityDensityScore (1-10): Rate 1-3 if it uses vague pronouns (it, they, we, our services). Rate 8-10 if it heavily incorporates hard, noun-based entities, unique brand tokens, and specific geographical markers.
- sentenceSimplicityScore (1-10): Rate 1-4 if the text contains complex, multi-clause sentences (25+ words). Rate 8-10 if sentences are punchy, short, and optimized for NLP dependency parsing.
- commodityContentScore (1-10): Rate 1-3 (High Commodity) if the text is pure standard AI fluff or textbook definitions. Rate 8-10 (Low Commodity / Premium) ONLY if it includes first-hand experience triggers ("In our experience..."), proprietary metrics, case studies, or explicit professional proof.

INSTRUCTIONS:
1. Evaluate the context and determine the exact "pageCategory".
2. Refine and confirm the final "score" based on how well this page adheres to its specific category standards, strictly respecting the scoring rules above.
3. Rigidly score the content sample from 1 to 10 against the 5 core pillars of AEO writing outlined in the STRICT AEO WRITING RUBRIC above:
   - bluffScore, atomicStructureScore, entityDensityScore, sentenceSimplicityScore, commodityContentScore.
4. Write an authoritative 3-paragraph "aiAnalysis" focusing on how conversational AI models (ChatGPT, Perplexity, Gemini) tokenize and perceive this specific brand entity. ${completelyBlocked
    ? "Since bot access is completely blocked, the first paragraph MUST clearly explain that AI crawlers cannot reach this site and what that means for AEO visibility. The remaining paragraphs may cover what could be improved once access is restored."
    : partiallyBlocked
    ? "Since a partial bot protection block is active, the first paragraph MUST address the access limitation and its practical impact on AI crawler indexing."
    : ""
  }
5. Generate exactly 5 prioritized, tactical objects inside the "recommendations" array.
   - For each recommendation, provide an 'id', 'title', 'severity' (CRITICAL, MEDIUM, LOW), 'category' (Technical, Semantic Layout, Entity & Trust, Content Optimization), detailed 'description', AEO 'impact', an array of string 'fixSteps', and an optional JSON-LD/HTML string snippet inside 'codeSnippet' if writing code solves it.

   ANTI-HALLUCINATION & ERROR REDUCTION RULES:
   - CRITICAL REQUIREMENT 1 (SCHEMAS): Look at the "DETECTED SCHEMA ENTITIES" provided above (${data.detectedSchemas.join(", ") || "None"}). You are STRICTLY FORBIDDEN from recommending the implementation of any Schema.org types that are ALREADY detected on the page.
   - CRITICAL REQUIREMENT 2 (SOCIAL PROFILES): Look at the KNOWLEDGE GRAPH FOOTPRINT MAP. If "LinkedIn Identity Profile", "X/Twitter Profile Anchor", or "Facebook Profile Anchor" are true, you are STRICTLY FORBIDDEN from generating a recommendation that tells the user to add, link, or implement that specific social media anchor.
   - CRITICAL REQUIREMENT 3 (DYNAMIC SNIPPETS): Any code generated inside the "codeSnippet" property MUST use the actual target domain/URL (${url}) and the real brand metadata tokens extracted from the context. Never use placeholders like "example.com" or "yourbrand.com".
   - CRITICAL REQUIREMENT 4 (NO OVERLAP): Each of the 5 recommendations must tackle a completely distinct issue. Do not duplicate concepts (e.g., do not generate two separate recommendations about headings or two about content length).
   - CRITICAL REQUIREMENT 5 (STRICT ARRAY FORMAT): Every item inside the "fixSteps" array must be a single, plain text string representing one step. Do NOT include markdown bolding (**), bullet points, or numbering strings inside the text strings themselves.

   ORDERING:
   - ${completelyBlocked || partiallyBlocked
      ? "Recommendation #1 MUST have an id of 'bot_access_block', severity 'CRITICAL', and be about resolving the bot access block. The remaining 4 recommendations may cover other AEO improvements."
      : "Order recommendations by highest AEO impact for this specific pageCategory."
    }
`;

  const aiResult = await model.generateContent(prompt);
  const responseText = aiResult.response.text();
  
  // Tipizirani povratak direktno iz parsiranog JSON-a
  return JSON.parse(responseText);
}